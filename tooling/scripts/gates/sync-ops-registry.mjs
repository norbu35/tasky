#!/usr/bin/env node

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import YAML from "yaml";
import {
    allowedToolingScriptLifecycles,
    listWorkflowFiles,
    loadOpsRegistry,
    readRepoFile,
    registryPath,
    repoRoot,
} from "./lib/ops-registry.mjs";

export const generatedInventoryPath = "docs/maintenance/generated/OPS_INVENTORY.md";

function markdownTable(headers, rows) {
    const escapeCell = (value) => String(value ?? "").replaceAll("|", "\\|");
    const tableRows = [headers, ...rows].map((row) => row.map(escapeCell));
    const widths = headers.map((_, columnIndex) =>
        Math.max(3, ...tableRows.map((row) => row[columnIndex]?.length ?? 0)),
    );
    const formatRow = (row) =>
        `| ${row.map((cell, columnIndex) => cell.padEnd(widths[columnIndex], " ")).join(" | ")} |`;
    const separator = `| ${widths.map((width) => "-".repeat(width)).join(" | ")} |`;

    return [formatRow(tableRows[0]), separator, ...tableRows.slice(1).map(formatRow)].join("\n");
}

function sortedEntries(record) {
    return Object.entries(record ?? {}).sort(([left], [right]) => left.localeCompare(right));
}

function commandList(values) {
    if (!values || values.length === 0) {
        return "";
    }
    return values.map((value) => `\`${value}\``).join("<br>");
}

export function sameStringSet(left, right) {
    return JSON.stringify([...new Set(left)].sort()) === JSON.stringify([...new Set(right)].sort());
}

export function describeArrayDelta(previous, next) {
    const previousSet = new Set(previous);
    const nextSet = new Set(next);
    return {
        added: [...nextSet].filter((item) => !previousSet.has(item)).sort(),
        removed: [...previousSet].filter((item) => !nextSet.has(item)).sort(),
    };
}

function formatArrayDelta(delta) {
    return `removed: [${delta.removed.join(", ") || "<none>"}]; added: [${delta.added.join(", ") || "<none>"}]`;
}

export function renderOpsInventory(registry) {
    const packageRows = sortedEntries(registry.packageScripts).map(([name, entry]) => [
        `\`${name}\``,
        entry.lifecycle,
        entry.lane ?? "",
        `\`${entry.command}\``,
    ]);

    const hookRows = sortedEntries(registry.hooks).map(([name, entry]) => [
        `\`${name}\``,
        entry.lifecycle,
        commandList(entry.requiredFragments ?? []),
    ]);

    const workflowRows = sortedEntries(registry.workflows).map(([name, entry]) => [
        `\`${name}\``,
        entry.lifecycle,
        commandList(entry.jobs ?? []),
        commandList(entry.requiredCommands ?? []),
    ]);

    const scriptRows = sortedEntries(registry.toolingScripts).map(([name, entry]) => [
        `\`${name}\``,
        entry.lifecycle,
        commandList(entry.referencePatterns ?? []),
    ]);

    const composeRows = (registry.composeFiles ?? []).map((name) => [`\`${name}\``]);

    return `<!-- Generated by \`pnpm repo:ops:sync --fix\`. Do not edit by hand. -->

# Ops Inventory

This file is generated from \`tooling/config/ops-registry.yaml\`.

\`docs/ops/diagrams/**\` are ephemeral human sketches and are not validation inputs.

## Package Scripts

${markdownTable(["Script", "Lifecycle", "Lane", "Command"], packageRows)}

## Hooks

${markdownTable(["Hook", "Lifecycle", "Required Fragments"], hookRows)}

## Workflows

${markdownTable(["Workflow", "Lifecycle", "Jobs", "Required Commands"], workflowRows)}

## Compose Files

${markdownTable(["Compose File"], composeRows)}

## Tooling Scripts

${markdownTable(["Script", "Lifecycle", "Reference Patterns"], scriptRows)}
`;
}

function discoverWorkflowJobs(workflowPath) {
    const parsed = YAML.parse(readRepoFile(workflowPath));
    return Object.keys(parsed?.jobs ?? {});
}

function cloneRegistry(registry) {
    return YAML.parse(YAML.stringify(registry));
}

function normalizeScriptPath(rawPath) {
    return rawPath.replace(/^tooling\/scripts\//, "").replaceAll(path.sep, "/");
}

function parseClassifications(args) {
    const classifications = [];
    for (let index = 0; index < args.length; index += 1) {
        if (args[index] !== "--classify") {
            continue;
        }
        const raw = args[index + 1];
        if (!raw || !raw.includes("=")) {
            throw new Error("--classify requires <tooling-script>=<lifecycle>");
        }
        index += 1;
        const [rawPath, lifecycle] = raw.split("=");
        classifications.push({ scriptPath: normalizeScriptPath(rawPath), lifecycle });
    }
    return classifications;
}

function applyClassifications(registry, classifications) {
    let changed = false;
    for (const { scriptPath, lifecycle } of classifications) {
        if (!allowedToolingScriptLifecycles.has(lifecycle)) {
            throw new Error(`invalid lifecycle '${lifecycle}' for ${scriptPath}`);
        }
        if (!existsSync(path.join(repoRoot, "tooling", "scripts", scriptPath))) {
            throw new Error(`cannot classify missing tooling script: ${scriptPath}`);
        }
        const previous = registry.toolingScripts?.[scriptPath]?.lifecycle;
        if (previous !== lifecycle) {
            registry.toolingScripts ??= {};
            registry.toolingScripts[scriptPath] = {
                ...(registry.toolingScripts[scriptPath] ?? {}),
                lifecycle,
            };
            changed = true;
        }
    }
    return changed;
}

function refreshWorkflowJobs(registry) {
    const changes = [];
    const workflowFiles = listWorkflowFiles();
    for (const workflowPath of workflowFiles) {
        if (!registry.workflows?.[workflowPath]) {
            continue;
        }
        const jobs = discoverWorkflowJobs(workflowPath);
        const current = registry.workflows[workflowPath].jobs ?? [];
        if (!sameStringSet(jobs, current)) {
            registry.workflows[workflowPath].jobs = jobs;
            changes.push({
                workflowPath,
                previous: current,
                next: jobs,
                delta: describeArrayDelta(current, jobs),
            });
        }
    }
    return changes;
}

function writeRegistry(registry) {
    writeFileSync(registryPath, YAML.stringify(registry, { lineWidth: 0 }));
}

function writeGeneratedInventory(registry) {
    const outputPath = path.join(repoRoot, generatedInventoryPath);
    mkdirSync(path.dirname(outputPath), { recursive: true });
    writeFileSync(outputPath, renderOpsInventory(registry));
}

function checkGeneratedInventory(registry) {
    const outputPath = path.join(repoRoot, generatedInventoryPath);
    const expected = renderOpsInventory(registry);
    if (!existsSync(outputPath)) {
        return [`${generatedInventoryPath} is missing`];
    }
    const actual = readFileSync(outputPath, "utf8");
    if (actual !== expected) {
        return [`${generatedInventoryPath} is stale`];
    }
    return [];
}

function checkWorkflowJobDrift(registry) {
    const failures = [];
    for (const workflowPath of listWorkflowFiles()) {
        if (!registry.workflows?.[workflowPath]) {
            failures.push(`${workflowPath} is not registered in tooling/config/ops-registry.yaml`);
            continue;
        }
        const actual = discoverWorkflowJobs(workflowPath);
        const expected = registry.workflows[workflowPath].jobs ?? [];
        if (!sameStringSet(actual, expected)) {
            failures.push(`${workflowPath} job list is stale (${formatArrayDelta(describeArrayDelta(expected, actual))})`);
        }
    }
    return failures;
}

function printRemediation() {
    console.error("autonomous remediation:");
    console.error(" - run: pnpm repo:ops:sync --fix");
    console.error(" - classify ambiguous new scripts explicitly with: pnpm repo:ops:sync --fix --classify tooling/scripts/path.ext=manual");
    console.error(" - keep docs/ops/diagrams/** out of registry and generated-doc checks");
}

export function runSync(args) {
    const fix = args.includes("--fix");
    const check = args.includes("--check") || !fix;
    const classifications = parseClassifications(args);
    const registry = fix ? cloneRegistry(loadOpsRegistry()) : loadOpsRegistry();

    if (fix) {
        const classificationsChanged = applyClassifications(registry, classifications);
        const workflowChanges = refreshWorkflowJobs(registry);
        const registryChanged = classificationsChanged || workflowChanges.length > 0;
        if (registryChanged) {
            writeRegistry(registry);
        }
        writeGeneratedInventory(registry);
        console.log("ops-registry-sync: wrote generated ops inventory");
        if (registryChanged) {
            console.log("ops-registry-sync: updated tooling/config/ops-registry.yaml");
            for (const change of workflowChanges) {
                console.log(
                    `ops-registry-sync: refreshed ${change.workflowPath} jobs (${formatArrayDelta(change.delta)})`,
                );
            }
        }
        return 0;
    }

    if (check) {
        const failures = [
            ...checkWorkflowJobDrift(registry),
            ...checkGeneratedInventory(registry),
        ];
        if (failures.length > 0) {
            console.error("ops-registry-sync: FAIL");
            for (const failure of failures) {
                console.error(` - ${failure}`);
            }
            printRemediation();
            return 1;
        }
        console.log("ops-registry-sync: PASS");
    }

    return 0;
}

const isCli = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isCli) {
    try {
        process.exit(runSync(process.argv.slice(2)));
    } catch (error) {
        console.error(`ops-registry-sync: FAIL (${error.message})`);
        printRemediation();
        process.exit(1);
    }
}
